// Copies db/schema.sql into lib/schema-sql.ts so the running app can create missing tables by itself.
import fs from 'node:fs';
const sql = fs.readFileSync(new URL('../db/schema.sql', import.meta.url), 'utf8');
fs.writeFileSync(new URL('../lib/schema-sql.ts', import.meta.url), '// GENERATED by scripts/gen-schema-ts.mjs from db/schema.sql - do not edit.\nexport const SCHEMA_SQL = ' + JSON.stringify(sql) + ';\n');
console.log('lib/schema-sql.ts written');
